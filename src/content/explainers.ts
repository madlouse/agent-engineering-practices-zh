export type FilmScene = {
  at: number;
  kicker: string;
  title: string;
  body?: string;
  wrong?: string;
  right?: string;
  cells?: string[];
  hold?: string;
  say: string;
};

export type Explainer = {
  slug: string;
  src: string;
  script: string;
  scenes: FilmScene[];
};

function film(slug: string, scenes: Array<Omit<FilmScene, "at">>): Explainer {
  const script = scenes.map((scene) => scene.say).join("");
  let cursor = 0;
  return {
    slug,
    src: `/explainers/${slug}.mp3`,
    script,
    scenes: scenes.map((scene) => {
      const at = script.length === 0 ? 0 : cursor / script.length;
      cursor += scene.say.length;
      return { ...scene, at };
    }),
  };
}

